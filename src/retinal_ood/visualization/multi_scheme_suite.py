def _sort_metrics(table: pd.DataFrame) -> pd.DataFrame:
    if table.empty:
        return table
    eval_rank = {name: index for index, name in enumerate(EVAL_SET_ORDER)}
    scheme_rank = {name: index for index, name in enumerate(SCHEME_ORDER)}
    table = table.copy()
    table["_eval_rank"] = table["eval_set"].map(lambda value: eval_rank.get(str(value), 99))
    table["_scheme_rank"] = table["scheme"].map(lambda value: scheme_rank.get(str(value), 99))
    table = table.sort_values(["_eval_rank", "_scheme_rank", "scheme"], kind="stable")
    return table.drop(columns=["_eval_rank", "_scheme_rank"]).reset_index(drop=True)


def _sort_category(table: pd.DataFrame, *, category: str, category_order: Sequence[str]) -> pd.DataFrame:
    if table.empty:
        return table
    eval_rank = {name: index for index, name in enumerate(EVAL_SET_ORDER)}
    scheme_rank = {name: index for index, name in enumerate(SCHEME_ORDER)}
    cat_rank = {name: index for index, name in enumerate(category_order)}
    table = table.copy()
    table["_eval_rank"] = table["eval_set"].map(lambda value: eval_rank.get(str(value), 99))
    table["_scheme_rank"] = table["scheme"].map(lambda value: scheme_rank.get(str(value), 99))
    table["_cat_rank"] = table[category].map(lambda value: cat_rank.get(str(value), 99))
    table = table.sort_values(["_eval_rank", "_scheme_rank", "_cat_rank", category], kind="stable")
    return table.drop(columns=["_eval_rank", "_scheme_rank", "_cat_rank"]).reset_index(drop=True)


