def _plot_failure_modes(records: Sequence[dict[str, Any]], path: Path, *, dpi: int) -> Path:
    rows: list[dict[str, Any]] = []
    for record in records:
        if record["eval_set"] != PRIMARY_EVAL_SET:
            continue
        scores = record["scores"]
        ood = scores[scores["label"].astype(int) == 1].copy()
        for ood_type in OOD_TYPE_ORDER:
            subset = ood[ood["ood_type"].astype(str) == ood_type]
            if subset.empty:
                continue
            miss_rate = float((subset["prediction"].astype(int) == 0).mean())
            rows.append(
                {
                    "scheme_label": SCHEME_LABELS.get(record["scheme"], record["scheme"]),
                    "ood_type": ood_type,
                    "miss_rate": miss_rate,
                }
            )
    table = pd.DataFrame(rows)
    fig, ax = plt.subplots(figsize=(8.2, 5.0))
    if table.empty:
        return _empty_plot(fig, ax, path, "No primary prediction rows available", dpi=dpi)
    table["ood_type"] = pd.Categorical(table["ood_type"], OOD_TYPE_ORDER, ordered=True)
    pivot = table.pivot_table(
        index="scheme_label",
        columns="ood_type",
        values="miss_rate",
        aggfunc="first",
        sort=False,
        observed=False,
    )
    _draw_heatmap(ax, pivot, title="OOD miss-rate failure modes by scheme", colorbar_label="Miss rate")
    return _save(fig, path, dpi=dpi)


