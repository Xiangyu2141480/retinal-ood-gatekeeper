def _load_run_records(run_roots: Sequence[RunRoot]) -> list[dict[str, Any]]:
    records: list[dict[str, Any]] = []
    seen: set[tuple[str, str]] = set()
    for root in run_roots:
        run_root = Path(root.path)
        runs_dir = run_root / "runs"
        if not runs_dir.exists():
            raise FileNotFoundError(f"Run root does not contain runs directory: {runs_dir}")
        for eval_dir in sorted(runs_dir.glob("*/evaluation")):
            metrics_path = eval_dir / "metrics.json"
            scores_path = eval_dir / "scores.csv"
            config_path = eval_dir / "resolved_evaluation_config.json"
            if not metrics_path.exists() or not scores_path.exists() or not config_path.exists():
                continue
            metrics = _read_json(metrics_path)
            config = _read_json(config_path)
            run_name = str(config.get("project", {}).get("run_name") or eval_dir.parent.name)
            scheme = _normalize_scheme(run_name, config)
            key = (root.eval_set, scheme)
            if key in seen:
                continue
            seen.add(key)
            scores = pd.read_csv(scores_path)
            scores = _prepare_scores(scores)
            records.append(
                {
                    "eval_set": root.eval_set,
                    "run_name": run_name,
                    "scheme": scheme,
                    "metrics": metrics,
                    "config": config,
                    "scores": scores,
                    "eval_dir": eval_dir,
                }
            )
    if not records:
        raise FileNotFoundError("No evaluation records found under the supplied run roots")
    return records


def _prepare_scores(scores: pd.DataFrame) -> pd.DataFrame:
    table = scores.copy()
    for column in ["label", "score", "threshold", "prediction"]:
        if column in table.columns:
            table[column] = pd.to_numeric(table[column], errors="coerce")
    if "ood_type" not in table.columns:
        table["ood_type"] = np.where(table["label"].astype(int) == 0, "id", "unknown")
    if "ood_subtype" not in table.columns:
        table["ood_subtype"] = np.where(table["label"].astype(int) == 0, "id", "unknown")
    if "prediction" not in table.columns:
        threshold = _first_numeric(table.get("threshold"))
        table["prediction"] = (table["score"].astype(float) >= threshold).astype(int) if threshold else 0
    return table


def _build_metrics_table(records: Sequence[dict[str, Any]]) -> pd.DataFrame:
    rows: list[dict[str, Any]] = []
    for record in records:
        metrics = record["metrics"]
        scores = record["scores"]
        labels = scores["label"].astype(int).to_numpy()
        values = scores["score"].astype(float).to_numpy()
        counts = metrics.get("counts", {})
        confusion = metrics.get("confusion_matrix", {})
        threshold_value = float(metrics.get("threshold", {}).get("value", _first_numeric(scores.get("threshold"))))
        id_count = int(counts.get("id", int((labels == 0).sum())))
        ood_count = int(counts.get("ood", int((labels == 1).sum())))
        fp = int(confusion.get("fp", int(((labels == 0) & (values >= threshold_value)).sum())))
        tp = int(confusion.get("tp", int(((labels == 1) & (values >= threshold_value)).sum())))
        rows.append(
            {
                "eval_set": record["eval_set"],
                "scheme": record["scheme"],
                "scheme_label": SCHEME_LABELS.get(record["scheme"], record["scheme"]),
                "run_name": record["run_name"],
                "method_family": SCHEME_SPECS.get(record["scheme"], _fallback_spec(record["scheme"])).method_family,
                "model": record["config"].get("model", {}).get("name", ""),
                "backbone": record["config"].get("model", {}).get("backbone", ""),
                "layers": _stringify_layers(record["config"].get("model", {}).get("layers", "")),
                "auroc": metrics.get("global", {}).get("auroc", np.nan),
                "auprc": metrics.get("global", {}).get("auprc", np.nan),
                "fpr_at_95_tpr": metrics.get("global", {}).get("fpr_at_95_tpr", np.nan),
                "threshold_at_95_tpr": _threshold_at_95_tpr(labels, values),
                "threshold": threshold_value,
                "threshold_source": metrics.get("threshold", {}).get("source", ""),
                "id_false_rejection_count": fp,
                "id_false_rejection_rate": fp / id_count if id_count else np.nan,
                "ood_recall_at_threshold": tp / ood_count if ood_count else np.nan,
                "id_count": id_count,
                "ood_count": ood_count,
                "total_count": int(counts.get("total", id_count + ood_count)),
                "notes": _row_notes(record),
            }
        )
    table = pd.DataFrame(rows)
    for column in ["auroc", "auprc", "fpr_at_95_tpr", "threshold_at_95_tpr"]:
        table[column] = pd.to_numeric(table[column], errors="coerce")
    return _sort_metrics(table)


def _build_per_type_table(records: Sequence[dict[str, Any]]) -> pd.DataFrame:
    rows: list[dict[str, Any]] = []
    for record in records:
        shared = _shared_row(record)
        for ood_type, values in sorted(record["metrics"].get("per_ood_type", {}).items()):
            rows.append(
                {
                    **shared,
                    "ood_type": ood_type,
                    "auroc": values.get("auroc", np.nan),
                    "auprc": values.get("auprc", np.nan),
                    "fpr_at_95_tpr": values.get("fpr_at_95_tpr", np.nan),
                    "id_count": values.get("id_count", np.nan),
                    "ood_count": values.get("ood_count", np.nan),
                }
            )
    return _sort_category(pd.DataFrame(rows), category="ood_type", category_order=OOD_TYPE_ORDER)


def _build_per_subtype_table(records: Sequence[dict[str, Any]]) -> pd.DataFrame:
    rows: list[dict[str, Any]] = []
    for record in records:
        scores = record["scores"]
        id_scores = scores[scores["label"].astype(int) == 0]
        shared = _shared_row(record)
        ood_scores = scores[scores["label"].astype(int) == 1].copy()
        for subtype in sorted(str(value) for value in ood_scores["ood_subtype"].dropna().unique() if value):
            subtype_scores = ood_scores[ood_scores["ood_subtype"].astype(str) == subtype]
            subset = pd.concat([id_scores, subtype_scores], ignore_index=True)
            metric_values = _safe_metrics(subset["label"].to_numpy(), subset["score"].to_numpy())
            rows.append(
                {
                    **shared,
                    "ood_type": _first_non_empty(subtype_scores["ood_type"].tolist()),
                    "ood_subtype": subtype,
                    **metric_values,
                    "id_count": int(len(id_scores)),
                    "ood_count": int(len(subtype_scores)),
                }
            )
    return _sort_category(pd.DataFrame(rows), category="ood_subtype", category_order=OOD_SUBTYPE_ORDER)


