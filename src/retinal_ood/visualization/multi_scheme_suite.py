def _stringify_layers(layers: Any) -> str:
    if isinstance(layers, (list, tuple)):
        return "+".join(str(layer) for layer in layers)
    if layers is None:
        return ""
    return str(layers)


def _threshold_at_95_tpr(labels: np.ndarray, scores: np.ndarray) -> float:
    labels = labels.astype(int)
    scores = scores.astype(float)
    if labels.size == 0 or len(np.unique(labels)) < 2:
        return float("nan")
    _, tpr, thresholds = roc_curve(labels, scores, pos_label=1, drop_intermediate=False)
    eligible = np.where(tpr >= 0.95)[0]
    if eligible.size == 0:
        return float("nan")
    finite = thresholds[eligible][np.isfinite(thresholds[eligible])]
    if finite.size == 0:
        return float("nan")
    return float(finite[0])


def _safe_metrics(labels: np.ndarray, scores: np.ndarray) -> dict[str, float]:
    try:
        result = compute_ood_metrics(labels.astype(int), scores.astype(float))
    except ValueError:
        return {"auroc": np.nan, "auprc": np.nan, "fpr_at_95_tpr": np.nan}
    return {
        "auroc": result.auroc,
        "auprc": result.auprc,
        "fpr_at_95_tpr": result.fpr_at_95_tpr,
    }


