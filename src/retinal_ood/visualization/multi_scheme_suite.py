def _build_scheme_overview(metrics: pd.DataFrame) -> pd.DataFrame:
    completed = set(metrics["scheme"].astype(str))
    rows: list[dict[str, Any]] = []
    for scheme in SCHEME_ORDER:
        spec = SCHEME_SPECS[scheme]
        status = "completed" if scheme in completed else "not_completed_runtime_limited"
        if scheme == "patchcore_l1" and scheme not in completed:
            reason = "Full L1 run was not completed because the shallow layer creates a dense patch grid."
        elif scheme not in completed:
            reason = "No completed evaluation artifact was available."
        else:
            reason = ""
        rows.append(
            {
                "scheme": spec.scheme,
                "scheme_label": spec.label,
                "method family": spec.method_family,
                "training data": spec.training_data,
                "score type": spec.score_type,
                "expected strength": spec.expected_strength,
                "expected weakness": spec.expected_weakness,
                "dissertation role": spec.dissertation_role,
                "completion_status": status,
                "completion_note": reason,
            }
        )
    return pd.DataFrame(rows)


def _primary_metrics(metrics: pd.DataFrame) -> pd.DataFrame:
    primary = metrics[metrics["eval_set"].astype(str) == PRIMARY_EVAL_SET].copy()
    if primary.empty:
        first_eval = sorted(metrics["eval_set"].astype(str).unique())[0]
        primary = metrics[metrics["eval_set"].astype(str) == first_eval].copy()
    return primary.reset_index(drop=True)


def _build_model_selection_summary(primary: pd.DataFrame) -> pd.DataFrame:
    if primary.empty:
        return pd.DataFrame()
    table = primary.copy()
    table["auroc_rank"] = table["auroc"].rank(ascending=False, method="min")
    table["auprc_rank"] = table["auprc"].rank(ascending=False, method="min")
    table["fpr95_rank"] = table["fpr_at_95_tpr"].rank(ascending=True, method="min")
    table["interpretability_score"] = table["scheme"].map(
        lambda scheme: SCHEME_SPECS.get(str(scheme), _fallback_spec(str(scheme))).interpretability
    )
    table["complexity_score"] = table["scheme"].map(
        lambda scheme: SCHEME_SPECS.get(str(scheme), _fallback_spec(str(scheme))).implementation_complexity
    )
    table["balanced_selection_score"] = (
        table["auroc"].fillna(0)
        + table["auprc"].fillna(0)
        + (1.0 - table["fpr_at_95_tpr"].fillna(1.0))
        + table["interpretability_score"].fillna(0)
        + (1.0 - table["complexity_score"].fillna(1.0))
    ) / 5.0
    table["recommendation"] = np.where(
        table["balanced_selection_score"] == table["balanced_selection_score"].max(),
        "selected_for_discussion",
        "comparison_baseline",
    )
    columns = [
        "eval_set",
        "scheme",
        "scheme_label",
        "method_family",
        "auroc",
        "auprc",
        "fpr_at_95_tpr",
        "id_false_rejection_rate",
        "ood_recall_at_threshold",
        "auroc_rank",
        "auprc_rank",
        "fpr95_rank",
        "interpretability_score",
        "complexity_score",
        "balanced_selection_score",
        "recommendation",
        "notes",
    ]
    return _sort_metrics(table.loc[:, columns])


def _write_table_pair(results_dir: Path, stem: str, table: pd.DataFrame, title: str) -> dict[str, Path]:
    csv_path = results_dir / f"{stem}.csv"
    md_path = results_dir / f"{stem}.md"
    table.to_csv(csv_path, index=False)
    note = (
        "Generated from compact evaluation metrics and score CSVs. Training remained ID-only; "
        "OOD labels were used only for evaluation grouping."
    )
    md_path.write_text(f"# {title}\n\n{note}\n\n{dataframe_to_markdown(table)}\n", encoding="utf-8")
    return {csv_path.name: csv_path, md_path.name: md_path}


